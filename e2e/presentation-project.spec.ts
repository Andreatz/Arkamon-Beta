import { test, expect, type BrowserContext, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

async function seed(context: BrowserContext) {
  await context.addInitScript(() => {
    if (localStorage.getItem('visual-project-fixture')) return
    const creature = (id: number) => ({ istanzaId: `PRIVATE_INSTANCE_${id}`, specieId: id === 1 ? 1 : 5, nome: id === 1 ? 'Vyrath in onda' : 'Darklaw riservato', livello: 10, hp: 8, xp: 0 })
    const player = (id: 1 | 2) => ({ id, nome: id === 1 ? 'Melia' : 'Maggi', squadra: id === 1 ? [creature(id), { ...creature(2), istanzaId: 'PRIVATE_TEAM_2', nome: 'Secondo compagno', hp: 3 }] : [creature(id)], deposito: id === 1 ? { '1:1': { ...creature(2), istanzaId: 'PRIVATE_RESERVE', nome: 'PRIVATE_RESERVE_NAME' } } : {}, cespugliVisitati: [], allenatoriSconfitti: [], caselleConsumate: [], monete: 700, inventario: { potion: 37 } })
    const place = { mappaId: 'mappa-principale', luogo: 'Venezia', x: 0, y: 0, direzione: 'S' }
    localStorage.setItem('arkamon-save', JSON.stringify({ version: 0, state: {
      giocatore1: player(1), giocatore2: player(2), giocatoreAttivo: 1, posizione1: place, posizione2: place,
      turnoOverworld: { giocatoreAttivo: 1, azioniRimaste: 2 }, scenaCorrente: { scena: 'mappa-principale' }, scenaPrecedente: null, battaglia: null, rivaleStarterId: 9, audioMuted: true,
    } }))
    localStorage.setItem('arkamon-preferences-v1', JSON.stringify({ version: 1, state: { musicVolume: 0, effectsVolume: 0, reducedMotion: 'on', animationSpeed: 'fast' } }))
    localStorage.setItem('visual-project-fixture', 'ready')
  })
}
async function ready(page: Page) {
  await page.goto('/')
  await expect(page.locator('[data-presented-scene]')).toHaveAttribute('aria-busy', 'false')
}
async function openProject(page: Page) {
  await page.getByRole('button', { name: 'Partita', exact: true }).press('Control+Shift+a')
  const admin = page.getByRole('region', { name: 'Modalità Admin', exact: true })
  await admin.getByRole('navigation', { name: 'Sezioni Admin' }).getByRole('button', { name: 'Progetto visivo', exact: true }).click()
  return admin.getByRole('region', { name: 'Progetto visivo', exact: true })
}
test.describe('presentation project and deliberate broadcast', () => {
  test.skip(({ isMobile }) => isMobile, 'The regia workspace runs on the desktop console.')
  test.beforeEach(async ({ page, context }) => { await page.setViewportSize({ width: 1920, height: 1080 }); await seed(context) })

  test('capture, apply, reload, export/import and rollback keep the campaign intact', async ({ page }) => {
    await ready(page)
    expect(await page.evaluate(() => JSON.parse(localStorage.getItem('arkamon-save')!).state.giocatore1.deposito['1:1'].nome)).toBe('PRIVATE_RESERVE_NAME')
    const campaign = await page.evaluate(() => JSON.parse(localStorage.getItem('arkamon-save')!).state)
    let panel = await openProject(page)
    await panel.getByLabel('Nome del progetto').fill('Regia di prova completa')
    await panel.getByRole('button', { name: 'Acquisisci impostazioni e bozze', exact: true }).click()
    await expect(panel.getByRole('status')).toContainText('Bozza acquisita')
    expect(await page.evaluate(() => JSON.parse(localStorage.getItem('arkamon-presentation-project-v1')!).applied)).toBeNull()
    await panel.getByRole('button', { name: 'Applica progetto al gioco', exact: true }).click()
    await expect(panel.getByRole('status')).toContainText('Progetto applicato e salvato')
    const downloadWait = page.waitForEvent('download')
    await panel.getByRole('button', { name: 'Esporta pacchetto', exact: true }).click()
    const download = await downloadWait, file = await download.path()
    const text = await readFile(file!, 'utf8'), bundle = JSON.parse(text)
    expect(bundle.format).toBe('arkamon-presentation')
    expect(bundle.project.name).toBe('Regia di prova completa')
    expect(text).not.toContain('PRIVATE_INSTANCE_')
    expect(text).not.toContain('PRIVATE_RESERVE')
    await page.reload()
    await expect(page.locator('[data-presented-scene]')).toHaveAttribute('aria-busy', 'false')
    // Admin can remain open after reload because its preference is durable.
    const admin = page.getByRole('region', { name: 'Modalità Admin', exact: true })
    const adminToggle = page.getByRole('button', { name: 'Admin', exact: true })
    await expect(adminToggle).toBeVisible()
    if (await adminToggle.getAttribute('aria-expanded') === 'false') await adminToggle.click()
    await expect(admin).toBeVisible()
    await admin.getByRole('navigation', { name: 'Sezioni Admin' }).getByRole('button', { name: 'Progetto visivo', exact: true }).click()
    panel = admin.getByRole('region', { name: 'Progetto visivo', exact: true })
    await expect(panel.locator('.arka-project-state').first()).toContainText('Regia di prova completa')
    await panel.getByLabel('Importa progetto visivo JSON').setInputFiles(file!)
    await expect(panel.getByRole('status')).toContainText('Pacchetto importato nella bozza')
    await panel.getByRole('button', { name: 'Scarta bozza', exact: true }).click()
    await panel.getByRole('button', { name: 'Ripristina progetto precedente', exact: true }).click()
    await expect(panel.getByRole('status')).toContainText('Progetto precedente ripristinato')
    expect(await page.evaluate(() => JSON.parse(localStorage.getItem('arkamon-save')!).state)).toEqual(campaign)
    await page.screenshot({ path: 'output/implementation-2026-10-19/progetto-visivo.png' })
  })

  test('private tools reveal only an explicitly selected detail and hide it on navigation', async ({ page, context }) => {
    await ready(page)
    const broadcast = await context.newPage()
    await broadcast.setViewportSize({ width: 1920, height: 1080 })
    await broadcast.goto('/?view=broadcast')
    await expect(broadcast.locator('[data-broadcast-view]')).toHaveAttribute('data-broadcast-connected', 'true')
    await page.getByRole('button', { name: 'Partita', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: 'La tua partita', exact: true })
    await dialog.getByRole('navigation', { name: 'Schermate del giocatore' }).getByRole('button', { name: 'Squadra', exact: true }).click()
    await expect(dialog.getByRole('heading', { name: 'Gestione squadra', exact: true })).toBeVisible()
    await expect(broadcast.getByRole('region', { name: 'Scheda presentata dal GM' })).toHaveCount(0)
    await dialog.getByRole('button', { name: 'Presenta scheda selezionata', exact: true }).click()
    const shown = broadcast.getByRole('region', { name: 'Scheda presentata dal GM' })
    await expect(shown).toContainText('Vyrath in onda')
    await expect(shown).not.toContainText('PRIVATE_RESERVE_NAME')
    await expect(shown).not.toContainText('Darklaw riservato')
    await expect(broadcast.getByRole('button')).toHaveCount(0)
    await broadcast.screenshot({ path: 'output/implementation-2026-10-19/scheda-in-onda.png' })
    await dialog.getByRole('button', { name: 'Nascondi dalla live', exact: true }).click()
    await expect(shown).toHaveCount(0)
    await dialog.getByRole('button', { name: 'Presenta scheda selezionata', exact: true }).click()
    await expect(shown).toBeVisible()
    await dialog.getByRole('navigation', { name: 'Schermate del giocatore' }).getByRole('button', { name: 'Deposito', exact: true }).click()
    await expect(shown).toHaveCount(0)
    await expect(dialog.getByRole('button', { name: 'Riprendi il Viaggio', exact: true })).toHaveCount(1)
  })

  test('keyboard selection, analysis and bag return to the same creature and focused command', async ({ page }) => {
    await ready(page)
    const before = await page.evaluate(() => JSON.parse(localStorage.getItem('arkamon-save')!).state)
    await page.getByRole('button', { name: 'Partita', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: 'La tua partita', exact: true })
    await dialog.getByRole('navigation', { name: 'Schermate del giocatore' }).getByRole('button', { name: 'Squadra', exact: true }).click()
    const slots = dialog.locator('.pu-team-slot:not(:disabled)')
    await slots.first().focus()
    await slots.first().press('ArrowDown')
    await expect(slots.nth(1)).toHaveAttribute('aria-pressed', 'true')
    const analyse = dialog.getByRole('button', { name: 'Analizza Arkamon', exact: true })
    await analyse.click()
    await expect(dialog.getByLabel('Arkamon da analizzare')).toHaveValue('PRIVATE_TEAM_2')
    const resume = dialog.getByRole('button', { name: 'Riprendi il Viaggio', exact: true })
    await resume.press('Escape')
    await expect(dialog.locator('.pu-shell')).toHaveAttribute('data-player-ui-screen', 'squadra')
    await expect(slots.nth(1)).toHaveAttribute('aria-pressed', 'true')
    await expect(analyse).toBeFocused()
    const bag = dialog.getByRole('button', { name: 'Apri borsa', exact: true })
    await bag.click()
    const target = dialog.getByLabel('Arkamon da curare')
    await expect(target).toHaveValue('PRIVATE_TEAM_2')
    await target.press('Escape')
    await expect(dialog.locator('.pu-shell')).toHaveAttribute('data-player-ui-screen', 'borsa')
    await resume.press('Escape')
    await expect(dialog.locator('.pu-shell')).toHaveAttribute('data-player-ui-screen', 'squadra')
    await expect(bag).toBeFocused()
    await resume.press('Escape')
    await expect(dialog).toHaveCount(0)
    expect(await page.evaluate(() => JSON.parse(localStorage.getItem('arkamon-save')!).state)).toEqual(before)
  })
})
