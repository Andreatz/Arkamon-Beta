import { expect, test, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

async function openStudio(page: Page) {
  await page.setViewportSize({ width: 1920, height: 1080 })
  await page.goto('/#ui-studio')
  await expect(page.locator('.uis-layer').first()).toBeVisible()
}
const preview = (page: Page) => page.frameLocator('.uis-canvas iframe')
async function title(page: Page) {
  await page.getByLabel('Schermata da modificare', { exact: true }).selectOption('titolo')
  await expect(preview(page).locator('[data-ui-id="logo"]')).toBeVisible()
  await page.getByLabel('Cerca elemento', { exact: true }).fill('Logo Arkamon')
  await page.locator('.uis-layer').filter({ hasText: 'Logo Arkamon' }).click()
  await expect(page.getByTestId('ui-studio-selection')).toBeVisible()
}
async function editorDraft(page: Page) {
  const pending = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Esporta', exact: true }).click()
  const download = await pending
  const bundle = JSON.parse(await readFile((await download.path())!, 'utf8'))
  return bundle.design
}

test.describe('complete visual editor workflow', () => {
  test.skip(({ isMobile }) => isMobile, 'The layout editor is a desktop workspace.')
  test('numeric position, drag, resize, history and Apply survive reload in the real game', async ({ page }) => {
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await openStudio(page)
    await title(page)
    await page.getByLabel('X', { exact: true }).fill('320')
    await page.getByLabel('Y', { exact: true }).fill('80')
    await page.getByLabel('Larghezza', { exact: true }).fill('720')
    await page.getByLabel('Altezza', { exact: true }).fill('180')
    const logo = preview(page).locator('[data-ui-id="logo"]')
    await expect(logo).toHaveCSS('width', '720px')
    await expect(logo).toHaveCSS('height', '180px')
    await expect(logo).toHaveCSS('left', '320px')
    await page.getByRole('checkbox', { name: 'Aggancio 8 px', exact: true }).uncheck()
    const selected = page.getByTestId('ui-studio-selection')
    const bounds = (await selected.boundingBox())!
    await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2)
    await page.mouse.down()
    await page.mouse.move(bounds.x + bounds.width / 2 + 40, bounds.y + bounds.height / 2 + 20, { steps: 5 })
    await page.mouse.up()
    await expect.poll(async () => Number(await page.getByLabel('X', { exact: true }).inputValue())).toBeGreaterThan(370)
    await page.getByRole('button', { name: '↶ Annulla', exact: true }).click()
    await expect(page.getByLabel('X', { exact: true })).toHaveValue('320')
    await page.getByRole('button', { name: '↷ Ripeti', exact: true }).click()
    const movedX = await page.getByLabel('X', { exact: true }).inputValue()
    const handle = (await page.getByRole('button', { name: 'Ridimensiona se', exact: true }).boundingBox())!
    await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2)
    await page.mouse.down()
    await page.mouse.move(handle.x + handle.width / 2 + 30, handle.y + handle.height / 2 + 15, { steps: 5 })
    await page.mouse.up()
    await expect.poll(async () => Number(await page.getByLabel('Larghezza', { exact: true }).inputValue())).toBeGreaterThan(750)
    await page.getByRole('button', { name: '↶ Annulla', exact: true }).click()
    await expect(page.getByLabel('Larghezza', { exact: true })).toHaveValue('720')
    await expect(page.getByLabel('X', { exact: true })).toHaveValue(movedX)
    await page.getByRole('button', { name: 'Applica al gioco', exact: true }).click()
    await expect(page.getByRole('status')).toContainText('Layout applicato')
    await page.reload()
    await expect(page.locator('.uis-layer').first()).toBeVisible()
    await title(page)
    await expect(page.getByLabel('X', { exact: true })).toHaveValue(movedX)
    await page.getByRole('button', { name: 'Esci', exact: true }).click()
    await expect(page.locator('.uis-root')).toHaveCount(0)
    await expect(page.locator('img[alt="Arkamon"]')).toHaveCSS('width', '720px')
    await expect(page.locator('img[alt="Arkamon"]')).toHaveCSS('height', '180px')
    expect(errors).toEqual([])
  })

  test('uploaded SVG and font are portable in export, render after reload, and Discard restores applied design', async ({ page }) => {
    await openStudio(page)
    const before = await page.evaluate(() => localStorage.getItem('arkamon-save'))
    await page.getByRole('button', { name: '+ Immagine', exact: true }).click()
    await page.getByRole('button', { name: 'Scegli asset', exact: true }).click()
    await page.getByLabel('Importa immagini', { exact: true }).setInputFiles({ name: 'test-emblema.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="120" height="120"><circle cx="60" cy="60" r="50" fill="#22cc88"/></svg>') })
    await page.getByRole('dialog', { name: 'Scegli asset', exact: true }).getByRole('button', { name: 'test-emblema.svg Importati', exact: true }).click()
    const draft = await editorDraft(page)
    const layerId = draft.screens.menu.layers[0].id
    await expect(preview(page).locator(`[data-ui-id="${layerId}"]`)).toHaveCSS('background-image', /(?:blob:|data:image\/svg\+xml)/)
    await page.getByRole('tab', { name: 'Font', exact: true }).click()
    await page.getByLabel('Importa caratteri', { exact: true }).setInputFiles('public/ui/studio/fonts/chela-one.ttf')
    await expect(page.getByRole('status')).toContainText('font importati')
    const headingFont = page.getByRole('combobox', { name: 'Carattere', exact: true }).nth(1)
    await headingFont.selectOption({ label: 'chela-one.ttf' })
    const customFontId = await headingFont.inputValue()
    await expect(preview(page).locator('.pu-page-head h1')).toHaveCSS('font-family', new RegExp(`UiUploaded_${customFontId}`))
    await expect.poll(() => preview(page).locator('body').evaluate((_, id) => Array.from(document.fonts).some(face => face.family === `UiUploaded_${id}` && face.status === 'loaded'), customFontId)).toBe(true)
    const download = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Esporta', exact: true }).click()
    const exported = await download
    const file = await exported.path()
    expect(file).toBeTruthy()
    await page.getByRole('button', { name: 'Applica al gioco', exact: true }).click()
    await page.reload()
    await expect(preview(page).locator(`[data-ui-id="${layerId}"]`)).toHaveCSS('background-image', /(?:blob:|data:image\/svg\+xml)/)
    await expect(preview(page).locator('.pu-page-head h1')).toHaveCSS('font-family', new RegExp(`UiUploaded_${customFontId}`))
    const persisted = await editorDraft(page)
    expect(persisted.media).toHaveLength(2)
    await page.getByRole('button', { name: '+ Testo', exact: true }).click()
    await page.getByRole('button', { name: 'Scarta', exact: true }).click()
    expect((await editorDraft(page)).screens.menu.layers).toHaveLength(1)
    await page.getByLabel('Importa layout JSON', { exact: true }).setInputFiles(file!)
    await expect(page.getByRole('status')).toContainText('Layout importato nella bozza')
    const imported = await editorDraft(page)
    expect(imported.media).toHaveLength(2)
    expect(imported.screens.menu.layers).toHaveLength(1)
    expect(await page.evaluate(() => localStorage.getItem('arkamon-save'))).toBe(before)
  })

  test('the actual menu accepts label, visibility and order changes without introducing shop navigation', async ({ page }) => {
    await openStudio(page)
    await page.getByRole('tab', { name: 'Menù', exact: true }).click()
    const diaryCommand = page.getByTestId('ui-studio-command-service.register')
    await diaryCommand.locator('input[type="text"],input:not([type])').fill('Registro di viaggio')
    const diary = preview(page).locator('.pu-menu-tile').first()
    await expect(diary).toContainText('Registro di viaggio')
    const backupMenu = page.getByTestId('ui-studio-command-service.backup')
    await backupMenu.getByRole('checkbox', { name: 'Visibile', exact: true }).uncheck()
    await expect(preview(page).locator('.pu-menu-tile').nth(1)).toHaveCSS('visibility', 'hidden')
    await expect(preview(page).locator('.pu-nav')).not.toContainText('Negozio')
    await diaryCommand.getByRole('button', { name: /^Sposta dopo / }).click()
    await expect(diary).toHaveCSS('order', '1')
    await page.getByRole('button', { name: 'Applica al gioco', exact: true }).click()
    await page.getByRole('button', { name: 'Esci', exact: true }).click()
    await page.getByRole('button', { name: 'Partita', exact: true }).click()
    await expect(page.locator('.pu-menu-tile').first()).toContainText('Registro di viaggio')
    await expect(page.locator('.pu-menu-tile').nth(1)).toHaveCSS('visibility', 'hidden')
    await expect(page.locator('.pu-nav')).not.toContainText('Negozio')
  })

  test('an inherited custom layer can be changed and removed only in a named internal view', async ({ page }) => {
    await openStudio(page)
    await page.getByLabel('Schermata da modificare', { exact: true }).selectOption('analisi')
    await expect(preview(page).locator('.pu-analysis-screen')).toBeVisible()
    await page.getByRole('button', { name: '+ Testo', exact: true }).click()
    await page.getByLabel('Nome nell’elenco', { exact: true }).fill('Nota base')
    await page.getByLabel('X', { exact: true }).fill('240')
    const layerId = (await preview(page).locator('[data-ui-runtime-owned="layer"]').getAttribute('data-ui-id'))!
    await page.getByLabel('Vista interna', { exact: true }).selectOption('mosse')
    await expect(preview(page).locator('.pu-analysis-screen')).toHaveAttribute('data-ui-view', 'mosse')
    await page.locator('.uis-layer').filter({ has: page.locator('strong', { hasText: /^Nota base$/ }) }).click()
    await page.getByLabel('X', { exact: true }).fill('400')
    await expect(page.getByLabel('X', { exact: true })).toHaveValue('400')
    await page.getByRole('button', { name: 'Elimina elemento', exact: true }).click()
    await expect(preview(page).locator(`[data-ui-id="${layerId}"]`)).toHaveCSS('visibility', 'hidden')
    await page.getByLabel('Vista interna', { exact: true }).selectOption('default')
    const layer = preview(page).locator(`[data-ui-id="${layerId}"]`)
    await expect(layer).toBeVisible()
    await expect(layer).toHaveCSS('left', '240px')
    await page.getByRole('button', { name: 'Applica al gioco', exact: true }).click()
    await page.reload()
    await expect(page.locator('.uis-layer').first()).toBeVisible()
    await page.getByLabel('Schermata da modificare', { exact: true }).selectOption('analisi')
    await expect(preview(page).locator(`[data-ui-id="${layerId}"]`)).toBeVisible()
    await page.getByLabel('Vista interna', { exact: true }).selectOption('mosse')
    await expect(preview(page).locator(`[data-ui-id="${layerId}"]`)).toHaveCSS('visibility', 'hidden')
  })

  test('an added button calls an existing real screen command after applying the design', async ({ page }) => {
    await openStudio(page)
    await page.getByRole('button', { name: '+ Pulsante', exact: true }).click()
    await page.getByRole('textbox', { name: 'Etichetta del pulsante', exact: true }).fill('Il mio registro')
    await page.getByRole('combobox', { name: 'Comando già presente nella schermata', exact: true }).selectOption('service.register')
    await page.getByRole('button', { name: 'Applica al gioco', exact: true }).click()
    await page.getByRole('button', { name: 'Esci', exact: true }).click()
    await page.getByRole('button', { name: 'Partita', exact: true }).click()
    await page.locator('[data-ui-runtime-owned="layer"]').filter({ hasText: 'Il mio registro' }).click()
    await expect(page.locator('.pu-shell')).toHaveAttribute('data-player-ui-screen', 'register')
  })
})
