import { expect, test } from '@playwright/test'

test('editing an inherited layer changes only the selected internal view', async ({ page, isMobile }) => {
  test.skip(isMobile, 'The visual editor is a desktop workspace.')
  await page.setViewportSize({ width: 1920, height: 1080 })
  await page.goto('/#ui-studio')
  const preview = page.frameLocator('.uis-canvas iframe')
  await expect(page.locator('.uis-layer').first()).toBeVisible()
  await page.getByLabel('Schermata da modificare', { exact: true }).selectOption('analisi')
  await expect(preview.locator('.pu-analysis-screen')).toBeVisible()
  await page.getByRole('button', { name: '+ Testo', exact: true }).click()
  await page.getByLabel('Nome nell’elenco', { exact: true }).fill('Richiamo allenatore')
  await page.getByRole('textbox', { name: 'Testo visualizzato', exact: true }).fill('Forza squadra')
  await page.getByLabel('X', { exact: true }).fill('240')
  const baseLayer = preview.locator('[data-ui-runtime-owned="layer"]').filter({ hasText: 'Forza squadra' })
  await expect(baseLayer).toHaveCSS('left', '240px')
  await page.getByLabel('Vista interna', { exact: true }).selectOption('mosse')
  await expect(preview.locator('[data-ui-studio-preview-screen]')).toHaveAttribute('data-ui-studio-preview-screen', 'analisi:mosse')
  await page.locator('.uis-layer').filter({ hasText: 'Richiamo allenatore' }).click()
  await expect(page.getByLabel('Nome nell’elenco', { exact: true })).toHaveValue('Richiamo allenatore')
  await page.getByLabel('X', { exact: true }).fill('480')
  await page.getByLabel('Nome nell’elenco', { exact: true }).fill('Richiamo mosse')
  await expect(baseLayer).toHaveCSS('left', '480px')
  await page.getByRole('button', { name: 'Elimina elemento', exact: true }).click()
  await expect(baseLayer).toHaveCSS('visibility', 'hidden')
  await page.getByLabel('Vista interna', { exact: true }).selectOption('default')
  await expect(preview.locator('[data-ui-studio-preview-screen]')).toHaveAttribute('data-ui-studio-preview-screen', 'analisi')
  await expect(baseLayer).toHaveCSS('left', '240px')
  await expect(baseLayer).toHaveCSS('visibility', 'visible')
  await page.locator('.uis-layer').filter({ hasText: 'Richiamo allenatore' }).click()
  await expect(page.getByLabel('Nome nell’elenco', { exact: true })).toHaveValue('Richiamo allenatore')
})
