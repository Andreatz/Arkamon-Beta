test('a configured interaction pays once, ends the turn and preserves separate player progress', async ({ page }) => {
  await page.goto('/')
  const errors: string[] = []; page.on('pageerror', (error) => errors.push(error.message))
  await page.getByRole('button', { name: 'Nuova Partita', exact: true }).click()
  await expect(page.locator('[data-presented-scene="laboratorio"]')).toHaveAttribute('aria-busy', 'false')
  await page.getByRole('button', { name: 'Continua', exact: true }).click()
  await page.getByRole('button', { name: /Vyrath/ }).click()
  await page.getByRole('button', { name: /Darklaw/ }).click()
  await expect(page.locator('[data-presented-scene="mappa-principale"]')).toHaveAttribute('aria-busy', 'false')
  await page.getByRole('button', { name: 'Admin', exact: true }).click()
  await page.getByRole('button', { name: 'Interazioni', exact: true }).click()
  const editor = page.getByRole('region', { name: 'Editor delle interazioni' })
  await editor.getByLabel('Titolo', { exact: true }).fill('Messaggio del ponte')
  await editor.getByLabel('Dialogo o istruzioni').fill('Hai trovato il primo indizio.')
  await editor.getByLabel('Monete da assegnare').fill('50')
  await editor.getByRole('button', { name: 'Salva interazione', exact: true }).click()
  await expect(editor.getByRole('status')).toHaveText('Interazione salvata.')
  await page.getByRole('button', { name: 'Chiudi', exact: true }).click()
  // Locate both players at this defined point without spending gameplay actions to reach it.
  const definition = await page.evaluate(() => {
    const catalog = JSON.parse(localStorage.getItem('arkamon-interactions-v1')!).state.interactions
    const entry = catalog[0]
    const saved = JSON.parse(localStorage.getItem('arkamon-save')!)
    saved.state.posizione1.luogo = entry.mapId; saved.state.posizione2.luogo = entry.mapId
    saved.state.posizioniLocali1 = { [entry.mapId]: entry.nodeId }
    saved.state.posizioniLocali2 = { [entry.mapId]: entry.nodeId }
    saved.state.scenaCorrente = { scena: 'citta', payload: { luogo: entry.mapId } }
    saved.state.giocatore1.monete = 100; saved.state.giocatore2.monete = 100
    localStorage.setItem('arkamon-save', JSON.stringify(saved))
    return entry
  })
  await page.reload()
  const scene = page.locator('[data-presented-scene="citta:Venezia"]')
  await expect(scene).toHaveAttribute('aria-busy', 'false')
  await scene.getByRole('button', { name: 'Interagisci sul punto', exact: true }).click()
  let interaction = page.getByRole('dialog', { name: 'Interazioni del punto' })
  await interaction.getByRole('button', { name: 'Interagisci', exact: true }).click()
  await expect(interaction.getByRole('button', { name: 'Completata', exact: true })).toBeDisabled()
  const completed = await page.evaluate(() => JSON.parse(localStorage.getItem('arkamon-save')!).state)
  expect(completed.giocatore1.monete).toBe(150)
  expect(completed.giocatore2.monete).toBe(100)
  expect(completed.interactionProgress.completed1).toEqual([definition.id])
  expect(completed.interactionProgress.completed2).toEqual([])
  expect(completed.turnoOverworld).toEqual({ giocatoreAttivo: 2, azioniRimaste: 2 })
  await page.keyboard.press('Escape'); await page.reload()
  await expect(scene).toHaveAttribute('aria-busy', 'false')
  await scene.getByRole('button', { name: 'Interagisci sul punto', exact: true }).click()
  interaction = page.getByRole('dialog', { name: 'Interazioni del punto' })
  await expect(interaction.getByRole('button', { name: 'Completata', exact: true })).toBeDisabled()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('arkamon-save')!).state.giocatore1.monete)).toBe(150)
  const a11y = await new AxeBuilder({ page }).include('.local-map-activities:not([hidden])').analyze()
  expect(a11y.violations).toEqual([])
  await test.info().attach('Interazione completata sulla mappa', { body: await page.screenshot(), contentType: 'image/png' })
  await page.keyboard.press('Escape')
  await scene.getByRole('button', { name: 'Passa turno', exact: true }).click()
  await scene.getByRole('button', { name: 'Interagisci sul punto', exact: true }).click()
  await page.getByRole('dialog', { name: 'Interazioni del punto' }).getByRole('button', { name: 'Interagisci', exact: true }).click()
  const both = await page.evaluate(() => JSON.parse(localStorage.getItem('arkamon-save')!).state)
  expect(both.giocatore1.monete).toBe(150); expect(both.giocatore2.monete).toBe(150)
  expect(both.interactionProgress.completed1).toEqual([definition.id])
  expect(both.interactionProgress.completed2).toEqual([definition.id])
  expect(errors).toEqual([])
})
