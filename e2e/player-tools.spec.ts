test('backup export, preview, cancellation and confirmed restore preserve the campaign', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Nuova Partita', exact: true }).click()
  await expect(page.locator('[data-presented-scene="laboratorio"]')).toHaveAttribute('aria-busy', 'false')
  await page.getByLabel('Giocatore 1', { exact: true }).fill('Backup Uno')
  await page.getByLabel('Giocatore 2', { exact: true }).fill('Backup Due')
  await page.getByRole('button', { name: 'Continua', exact: true }).click()
  await page.getByRole('button', { name: /Vyrath/ }).click()
  await page.getByRole('button', { name: /Darklaw/ }).click()
  await expect(page.locator('[data-presented-scene="mappa-principale"]')).toHaveAttribute('aria-busy', 'false')
  const before = await page.evaluate(() => localStorage.getItem('arkamon-save'))
  const dialog = await tools(page, 'Backup')
  const downloadPromise = page.waitForEvent('download')
  await dialog.getByRole('button', { name: 'Scarica backup partita', exact: true }).click()
  const download = await downloadPromise
  const text = await readFile((await download.path())!, 'utf8')
  const saved = JSON.parse(text)
  expect(saved.version).toBe(1)
  expect(saved.campaign.giocatore1.squadra[0].hp).toBeGreaterThan(0)
  await dialog.getByLabel('Importa backup partita').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{"hello":"world"}') })
  await expect(dialog.getByRole('alert')).toContainText('non è un backup')
  expect(await page.evaluate(() => localStorage.getItem('arkamon-save'))).toBe(before)
  await dialog.getByLabel('Importa backup partita').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(text) })
  await expect(dialog.getByLabel('Anteprima ripristino')).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Ripristina questa partita' })).toBeDisabled()
  await dialog.getByRole('button', { name: 'Annulla importazione' }).click()
  expect(await page.evaluate(() => localStorage.getItem('arkamon-save'))).toBe(before)
  saved.campaign.giocatore1.nome = 'Ripristinato'
  saved.campaign.giocatore1.squadra[0].hp = 3
  await dialog.getByLabel('Importa backup partita').setInputFiles({ name: 'updated.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(saved)) })
  await dialog.getByRole('checkbox', { name: /Confermo la sostituzione/ }).check()
  await dialog.getByRole('button', { name: 'Ripristina questa partita' }).click()
  await expect(dialog.getByRole('status')).toContainText('Partita ripristinata')
  await expect(dialog.getByRole('button', { name: 'Scarica backup precedente' })).toBeVisible()
  await page.keyboard.press('Escape'); await page.reload()
  const restored = await page.evaluate(() => JSON.parse(localStorage.getItem('arkamon-save') || '{}').state)
  expect(restored.giocatore1.nome).toBe('Ripristinato')
  expect(restored.giocatore1.squadra[0].hp).toBe(3)
  expect(restored.giocatore2.squadra[0].specieId).toBe(5)
})

