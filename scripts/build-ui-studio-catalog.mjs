import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const entries = []
async function scan(relative) {
  for (const entry of await fs.readdir(path.join(root, 'public', relative), { withFileTypes: true })) {
    const next = `${relative}/${entry.name}`
    if (entry.isDirectory()) await scan(next)
    else if (/\.(svg|png|jpg|jpeg|webp|gif|avif)$/i.test(entry.name)) entries.push({
      id: `builtin:${next}`, name: entry.name.replace(/\.[^.]+$/, '').replaceAll('-', ' '),
      source: `/${next}`, category: next.startsWith('ui/studio/') ? next.split('/').slice(2, -1).join(' · ') || 'Kit aggiornato'
        : next.startsWith('ui/reference-png/') ? 'UI PNG fornita'
        : next.startsWith('backgrounds/arkamon-splash/') ? 'Splash Arkamon'
        : relative.startsWith('backgrounds') ? 'Sfondi del gioco' : 'Asset originali', kind: 'image',
    })
  }
}
await scan('ui')
await scan('backgrounds')
entries.sort((a, b) => a.source.localeCompare(b.source))
const output = `// Generated by scripts/build-ui-studio-catalog.mjs.\nimport type { UiBuiltinAsset } from './types'\n\nexport const UI_BUILTIN_ASSETS: UiBuiltinAsset[] = ${JSON.stringify(entries, null, 2)}\n\nexport function getUiFontFamily(id: string): string {\n  if (id === 'norwester') return "'Arkamon Norwester', 'Arial Narrow', Arial, sans-serif"\n  if (id === 'chela') return "'Chela One', Arial, sans-serif"\n  if (id === 'azonix') return "'Azonix', Arial, sans-serif"\n  if (id === 'system') return 'system-ui, sans-serif'\n  return "'UiUploaded_" + id.replace(/[^a-zA-Z0-9_-]/g, '_') + "', 'Arkamon Norwester', Arial, sans-serif"\n}\n`
await fs.writeFile(path.join(root, 'src/ui-studio/assetCatalog.ts'), output)
console.log(`UI catalog: ${entries.length} image assets`)
